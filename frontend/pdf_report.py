def _verdict_block(run: dict[str, Any]) -> Any:
    weighted = float(run.get("weighted_total") or 0.0)
    max_weighted = float(run.get("max_weighted_total") or 0.0) or 1.0
    threshold = run.get("overall_threshold")
    passed = (threshold is None) or (weighted >= threshold)
    frac = weighted / max_weighted
    accent = C_POS if passed else C_NEG

    donut = _Donut(frac, C_AMBER if passed else C_NEG, size=40 * mm)

    if threshold is None:
        margin_sub = "no threshold configured"
        thr_val, thr_sub = "—", "not set for this run"
    else:
        delta = weighted - float(threshold)
        margin_sub = f"{'+' if delta >= 0 else '−'}{abs(delta):g} against threshold"
        thr_val = f"{float(threshold):g}"
        thr_sub = f"{float(threshold) / max_weighted * 100:.0f}% of maximum"

    tiles = _Tiles(
        [
            ("Weighted total", f"{weighted:g}", f"of {max_weighted:g} maximum", C_NAVY),
            ("Pass threshold", thr_val, thr_sub, C_AMBER),
            ("Outcome", "PASS" if passed else "FAIL", margin_sub, accent),
            ("Predicted band", str(run.get("predicted_band") or "—"), "model estimate", C_LINE_STRONG),
        ],
        width=CONTENT_W - 46 * mm,
        height=19 * mm,
        columns=2,
    )

    t = Table([[donut, tiles]], colWidths=[46 * mm, CONTENT_W - 46 * mm], hAlign="LEFT")
    t.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (0, 0), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("LEFTPADDING", (1, 0), (1, 0), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
    ]))
    return t


def _score_chart(criteria: list[dict[str, Any]]) -> _BarChart | None:
    rows = []
    for c in criteria:
        max_score = float(c.get("max_score") or 5.0) or 5.0
        score = float(c.get("score") or 0.0)
        frac = max(0.0, min(1.0, score / max_score))
        rows.append((
            str(c.get("name") or "—"),
            score,
            max_score,
            colors.HexColor(theme.score_color(frac)),
            f"{score:g} / {max_score:g}",
        ))
    if not rows:
        return None
    # Every bar shares the largest max_score so lengths stay comparable.
    return _BarChart(rows, width=CONTENT_W, axis_max=max(r[2] for r in rows))


def _contribution_chart(criteria: list[dict[str, Any]]) -> _BarChart | None:
    rows = []
    for c in criteria:
        weight = float(c.get("weight") or 0.0)
        max_score = float(c.get("max_score") or 5.0) or 5.0
        score = float(c.get("score") or 0.0)
        rows.append((
            str(c.get("name") or "—"),
            score * weight,
            max_score * weight,
            C_NAVY,
            f"{score * weight:g}",
        ))
    if not rows:
        return None
    return _BarChart(rows, width=CONTENT_W, axis_max=max(r[2] for r in rows))


def _bullets(items: list[str] | None, empty: str = "None recorded.") -> list[Any]:
    clean = [str(i).strip() for i in (items or []) if str(i or "").strip()]
    if not clean:
        return [Paragraph(escape(empty), _BULLET_NONE, bulletText="–")]
    return [Paragraph(_p(i), _BULLET, bulletText="•") for i in clean]


def _criterion_detail(c: dict[str, Any]) -> list[Any]:
    score = float(c.get("score") or 0.0)
    max_score = float(c.get("max_score") or 5.0) or 5.0
    frac = max(0.0, min(1.0, score / max_score))
    accent = colors.HexColor(theme.score_color(frac))

    block: list[Any] = [
        _CritHead(
            str(c.get("name") or "—"), score, max_score,
            float(c.get("weight") or 0.0),
            (c.get("band") or "").title(), accent,
        ),
    ]

    coverage_bits = [f"Confidence: {(c.get('confidence') or '—').title()}"]
    if c.get("full_document_input"):
        coverage_bits.append("Input: full document")
    elif c.get("input_coverage") is not None:
        coverage_bits.append(
            f"Input: excerpts (~{float(c['input_coverage']) * 100:.0f}% of document)"
        )
    block.append(Paragraph(" · ".join(escape(b) for b in coverage_bits), _FOOTNOTE))

    block.append(Paragraph("STRENGTHS", _LABEL))
    block += _bullets(c.get("strengths"), "None recorded.")

    block.append(Paragraph("WEAKNESSES", _LABEL))
    block += _bullets(c.get("weaknesses"), "No significant weaknesses identified.")

    if c.get("missing_evidence"):
        block.append(Paragraph("MISSING EVIDENCE", _LABEL))
        block += _bullets(c.get("missing_evidence"))

    if c.get("input_gaps"):
        block.append(Paragraph("INPUT GAPS  (not seen by the model — not penalised)", _LABEL))
        block += _bullets(c.get("input_gaps"))

    if c.get("evaluator_comment"):
        block.append(Paragraph("EVALUATOR COMMENT", _LABEL))
        block.append(Paragraph(_p(c["evaluator_comment"]), _COMMENT))

    if c.get("recommendations"):
        block.append(Paragraph("RECOMMENDATIONS", _LABEL))
        block += _bullets(c.get("recommendations"))

    block.append(Spacer(1, 11))
    return block


