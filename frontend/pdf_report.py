def run_to_pdf(run: dict[str, Any]) -> bytes:
    """Render one evaluation run as a formatted PDF report."""
    buf = io.BytesIO()
    acronym = str(run.get("proposal_acronym") or "Proposal")
    call_id = str(run.get("call_id") or "")

    doc = BaseDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=M_L, rightMargin=M_R, topMargin=M_T, bottomMargin=M_B,
        title=f"EDF evaluation — {acronym}",
        author="IKH Defence Labs · EDF Proposal Evaluator",
        subject=f"Automated pre-screening of {acronym} ({call_id})",
    )
    frame = Frame(
        M_L, M_B, CONTENT_W, PAGE_H - M_T - M_B,
        leftPadding=0, rightPadding=0, topPadding=0, bottomPadding=0, id="body",
    )
    doc.addPageTemplates([PageTemplate(id="all", frames=[frame])])

    criteria = run.get("criteria") or []
    story: list[Any] = []
    story += _cover(run)

    story.append(_SectionHead("Verdict", hint="weighted result against the configured threshold"))
    story.append(_verdict_block(run))

    if run.get("ingest_warning"):
        story.append(Spacer(1, 9))
        warn = Table(
            [[Paragraph(f"<b>Ingestion warning</b>  {_p(run['ingest_warning'])}", _CELL)]],
            colWidths=[CONTENT_W], hAlign="LEFT",
        )
        warn.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), C_AMBER_TINT),
            ("BOX", (0, 0), (-1, -1), 0.6, C_AMBER),
            ("LINEBEFORE", (0, 0), (0, 0), 2.4, C_AMBER),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ]))
        story.append(warn)

    summary = run.get("esr_style_summary") or "—"
    story.append(_SectionHead("Assessment summary", hint="ESR style"))
    for para in [p.strip() for p in str(summary).split("\n") if p.strip()] or ["—"]:
        story.append(Paragraph(_p(para), _BODY))

    score_chart = _score_chart(criteria)
    if score_chart is not None:
        story.append(_SectionHead("Score profile", hint="score against the maximum per criterion"))
        story.append(score_chart)

    contrib_chart = _contribution_chart(criteria)
    if contrib_chart is not None:
        story.append(_SectionHead(
            "Weighted contribution", hint="score × weight against the weighted cap",
        ))
        story.append(contrib_chart)

    if criteria:
        story.append(_SectionHead("Scoring table"))
        story.append(_criteria_table(criteria))

        story.append(_SectionHead("Criterion detail"))
        for c in criteria:
            # Keep at least the banner with its first findings on one page.
            block = _criterion_detail(c)
            story.append(KeepTogether(block[:4]))
            story += block[4:]

    story.append(Spacer(1, 6))
    story.append(_Rule(CONTENT_W, thickness=0.6, color=C_LINE, accent_w=22 * mm))
    story.append(Spacer(1, 5))
    story.append(Paragraph(escape(run.get("notes") or DISCLAIMER), _FOOTNOTE))

    def _mk_canvas(*args: Any, **kwargs: Any) -> _Canvas:
        kwargs["edf_meta"] = {"acronym": acronym, "call_id": call_id}
        return _Canvas(*args, **kwargs)

    doc.build(story, canvasmaker=_mk_canvas)
    return buf.getvalue()
