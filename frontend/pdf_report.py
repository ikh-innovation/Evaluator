def _p(text: Any) -> str:
    """Escape model-authored text for a Paragraph, keeping line breaks."""
    return escape(str(text if text is not None else "")).replace("\n", "<br/>")


def _fit(text: str, font: str, size: float, max_w: float) -> str:
    """Trim `text` with an ellipsis so it fits `max_w` points."""
    text = str(text or "")
    if stringWidth(text, font, size) <= max_w:
        return text
    ell = "…"
    lo, hi = 0, len(text)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if stringWidth(text[:mid] + ell, font, size) <= max_w:
            lo = mid
        else:
            hi = mid - 1
    return text[:lo].rstrip() + ell


def _spaced(canv, x: float, y: float, text: str, tracking: float = 0.7) -> None:
    """Draw letter-spaced text (used for the small uppercase labels).

    Character spacing is a text-object property, not a canvas one, so this
    goes through beginText — which inherits the canvas font and fill.
    """
    tx = canv.beginText(x, y)
    tx.setCharSpace(tracking)
    tx.textOut(text)
    canv.drawText(tx)


def _spaced_width(text: str, font: str, size: float, tracking: float) -> float:
    return stringWidth(text, font, size) + tracking * max(0, len(text) - 1)


