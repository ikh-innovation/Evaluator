class _Rule(Flowable):
    """A horizontal rule; optionally an amber lead-in over a hairline."""

    def __init__(self, width: float, thickness: float = 0.6,
                 color: colors.Color = C_LINE, accent_w: float = 0.0,
                 space_before: float = 0.0, space_after: float = 0.0):
        super().__init__()
        self._w = width
        self._t = thickness
        self._c = color
        self._accent = accent_w
        self._sb = space_before
        self._sa = space_after

    def wrap(self, aw, ah):
        return (self._w, self._t + self._sb + self._sa)

    def draw(self):
        y = self._sa
        self.canv.setLineWidth(self._t)
        self.canv.setStrokeColor(self._c)
        self.canv.line(0, y, self._w, y)
        if self._accent:
            self.canv.setLineWidth(max(self._t, 1.6))
            self.canv.setStrokeColor(C_AMBER)
            self.canv.line(0, y, self._accent, y)


class _SectionHead(Flowable):
    """Uppercase section label with an amber tick and a rule to the margin."""

    H = 15

    def __init__(self, label: str, width: float = CONTENT_W, hint: str = "",
                 space_before: float = 9):
        super().__init__()
        self._label = label.upper()
        self._hint = hint
        self._w = width
        self._sb = space_before

    def wrap(self, aw, ah):
        return (self._w, self.H + 8 + self._sb)

    def draw(self):
        c = self.canv
        base = 8
        # amber tick
        c.setFillColor(C_AMBER)
        c.rect(0, base, 2.6, 8.4, stroke=0, fill=1)
        # label
        c.setFillColor(C_NAVY)
        c.setFont(FONT_B, 8.2)
        _spaced(c, 7, base + 1.4, self._label, 1.0)
        x = 7 + _spaced_width(self._label, FONT_B, 8.2, 1.0) + 8
        if self._hint:
            c.setFillColor(C_MUTED)
            c.setFont(FONT, 7.4)
            hint = _fit(self._hint, FONT, 7.4, self._w - x - 10)
            c.drawString(x, base + 1.6, hint)
            x += stringWidth(hint, FONT, 7.4) + 8
        if x < self._w:
            c.setStrokeColor(C_LINE)
            c.setLineWidth(0.6)
            c.line(x, base + 4, self._w, base + 4)


class _Donut(Flowable):
    """Achievement donut with the percentage in the middle."""

    def __init__(self, frac: float, accent: colors.Color, size: float = 46 * mm,
                 caption: str = "of maximum"):
        super().__init__()
        self._frac = max(0.0, min(1.0, float(frac)))
        self._accent = accent
        self._size = size
        self._caption = caption

    def wrap(self, aw, ah):
        return (self._size, self._size)

    def draw(self):
        c = self.canv
        s = self._size
        cx = cy = s / 2
        r_out = s * 0.44
        r_in = s * 0.315
        box = (cx - r_out, cy - r_out, cx + r_out, cy + r_out)

        # track
        c.setFillColor(C_ALT)
        c.circle(cx, cy, r_out, stroke=0, fill=1)
        # achieved wedge, clockwise from 12 o'clock
        if self._frac > 0:
            c.setFillColor(self._accent)
            c.wedge(*box, 90, -360 * self._frac, stroke=0, fill=1)
        # punch the hole
        c.setFillColor(C_WHITE)
        c.circle(cx, cy, r_in, stroke=0, fill=1)
        c.setStrokeColor(C_LINE)
        c.setLineWidth(0.5)
        c.circle(cx, cy, r_out, stroke=1, fill=0)

        pct = f"{self._frac * 100:.0f}%"
        c.setFillColor(C_NAVY)
        c.setFont(FONT_B, s * 0.19)
        c.drawCentredString(cx, cy + s * 0.02, pct)
        c.setFillColor(C_MUTED)
        c.setFont(FONT, s * 0.062)
        c.drawCentredString(cx, cy - s * 0.115, self._caption)


class _Tiles(Flowable):
    """A row of metric tiles matching the on-screen ones: hairline box,
    coloured left edge, uppercase label, large tabular value."""

    def __init__(self, items: list[tuple[str, str, str, colors.Color]],
                 width: float = CONTENT_W, height: float = 20 * mm,
                 gap: float = 5, columns: int | None = None):
        super().__init__()
        self._items = items
        self._w = width
        self._h = height
        self._gap = gap
        self._cols = columns or len(items)

    def wrap(self, aw, ah):
        rows = -(-len(self._items) // self._cols)
        return (self._w, rows * self._h + (rows - 1) * self._gap)

    def draw(self):
        c = self.canv
        cols = self._cols
        rows = -(-len(self._items) // cols)
        bw = (self._w - self._gap * (cols - 1)) / cols
        total_h = rows * self._h + (rows - 1) * self._gap
        for i, (label, value, sub, accent) in enumerate(self._items):
            r, col = divmod(i, cols)
            x = col * (bw + self._gap)
            y = total_h - (r + 1) * self._h - r * self._gap
            c.setFillColor(C_WHITE)
            c.setStrokeColor(C_LINE)
            c.setLineWidth(0.6)
            c.roundRect(x, y, bw, self._h, 2.5, stroke=1, fill=1)
            c.setFillColor(accent)
            c.rect(x, y + 1.2, 2.4, self._h - 2.4, stroke=0, fill=1)

            pad = 7
            c.setFillColor(C_MUTED)
            c.setFont(FONT_B, 6.4)
            _spaced(c, x + pad, y + self._h - 8.5,
                    _fit(label.upper(), FONT_B, 6.4, bw - pad * 2), 0.7)
            c.setFillColor(C_NAVY if accent in (C_NAVY, C_AMBER, C_LINE_STRONG) else accent)
            # Shrink long values (band names run to ~25 chars) rather than
            # clipping them — the whole label carries meaning here.
            avail = bw - pad - 8
            size = 14.0
            while size > 8.0 and stringWidth(value, FONT_B, size) > avail:
                size -= 0.5
            c.setFont(FONT_B, size)
            c.drawString(x + pad, y + self._h - 11 - size, _fit(value, FONT_B, size, avail))
            if sub:
                c.setFillColor(C_MUTED)
                c.setFont(FONT, 6.8)
                c.drawString(x + pad, y + 5.4, _fit(sub, FONT, 6.8, bw - pad * 2))


class _BarChart(Flowable):
    """Horizontal bars on a light track: label · track+fill · value.

    rows: (label, value, cap, fill_colour, value_text)
    """

    def __init__(self, rows: list[tuple[str, float, float, colors.Color, str]],
                 width: float = CONTENT_W, row_h: float = 15.5,
                 label_w: float | None = None, value_w: float = 42,
                 bar_h: float = 7.5, axis_max: float | None = None):
        super().__init__()
        self._rows = rows
        self._w = width
        self._rh = row_h
        self._lw = label_w if label_w is not None else width * 0.42
        self._vw = value_w
        self._bh = bar_h
        self._axis_max = axis_max

    def wrap(self, aw, ah):
        return (self._w, len(self._rows) * self._rh)

    def draw(self):
        c = self.canv
        top = len(self._rows) * self._rh
        x_bar = self._lw + 8
        bar_w = self._w - x_bar - self._vw
        axis_max = self._axis_max or max([r[2] for r in self._rows] or [1]) or 1

        for i, (label, value, cap, fill, vtext) in enumerate(self._rows):
            cy = top - (i + 0.5) * self._rh
            y = cy - self._bh / 2

            c.setFillColor(C_INK)
            c.setFont(FONT, 8.3)
            c.drawString(0, cy - 2.9, _fit(label, FONT, 8.3, self._lw))

            track_w = bar_w * (cap / axis_max) if axis_max else bar_w
            c.setFillColor(C_ALT)
            c.roundRect(x_bar, y, max(track_w, 1), self._bh, 1.8, stroke=0, fill=1)

            fill_w = bar_w * (value / axis_max) if axis_max else 0
            if fill_w > 0.6:
                c.setFillColor(fill)
                c.roundRect(x_bar, y, fill_w, self._bh, 1.8, stroke=0, fill=1)

            c.setFillColor(C_INK)
            c.setFont(FONT_B, 8.1)
            c.drawRightString(self._w, cy - 2.9, vtext)


class _CritHead(Flowable):
    """Banner for one criterion: coloured tick, name, band/weight, score box.

    Criterion names are long (EDF award-criterion wording runs to ~90
    characters), so the name wraps onto a second line and the banner grows
    rather than the name being clipped.
    """

    PAD_V = 6.5
    NAME_SIZE = 9.8
    NAME_LEAD = 11.6
    MAX_LINES = 2

    def __init__(self, name: str, score: float, max_score: float, weight: float,
                 band: str, accent: colors.Color, width: float = CONTENT_W):
        super().__init__()
        self._name = str(name or "—")
        self._score = score
        self._max = max_score
        self._weight = weight
        self._band = band
        self._accent = accent
        self._w = width

        self._score_txt = f"{score:g} / {max_score:g}"
        self._box_w = stringWidth(self._score_txt, FONT_B, 9.4) + 14
        meta = f"weight ×{weight:g}"
        if band and band != "—":
            meta = f"{band}  ·  {meta}"
        self._meta = meta
        self._meta_w = stringWidth(meta, FONT, 7.4)
        self._name_w = self._w - self._box_w - self._meta_w - 30
        self._lines = self._wrap_name()
        self._h = max(21.0, len(self._lines) * self.NAME_LEAD + self.PAD_V * 2)

    def _wrap_name(self) -> list[str]:
        """Greedy word wrap onto at most MAX_LINES, last line ellipsised."""
        words = self._name.split()
        if not words:
            return ["—"]
        lines: list[str] = []
        cur = ""
        for word in words:
            trial = f"{cur} {word}".strip()
            if stringWidth(trial, FONT_B, self.NAME_SIZE) <= self._name_w or not cur:
                cur = trial
            else:
                lines.append(cur)
                cur = word
                if len(lines) == self.MAX_LINES - 1:
                    break
        rest = self._name[len(" ".join(lines)):].strip() if lines else cur
        lines.append(_fit(rest or cur, FONT_B, self.NAME_SIZE, self._name_w))
        return lines[: self.MAX_LINES]

    def wrap(self, aw, ah):
        return (self._w, self._h + 4)

    def draw(self):
        c = self.canv
        y, h = 4, self._h
        c.setFillColor(C_ALT)
        c.setStrokeColor(C_LINE)
        c.setLineWidth(0.6)
        c.roundRect(0, y, self._w, h, 2.5, stroke=1, fill=1)
        c.setFillColor(self._accent)
        c.rect(0, y + 1.2, 2.6, h - 2.4, stroke=0, fill=1)

        c.setFillColor(C_NAVY)
        c.setFont(FONT_B, self.NAME_SIZE)
        top = y + h - self.PAD_V - self.NAME_SIZE + 1.4
        for i, line in enumerate(self._lines):
            c.drawString(9, top - i * self.NAME_LEAD, line)

        # Band + weight and the score box are pinned to the vertical centre.
        c.setFillColor(C_MUTED)
        c.setFont(FONT, 7.4)
        c.drawRightString(self._w - self._box_w - 10, y + h / 2 - 2.6, self._meta)

        bx = self._w - self._box_w - 4
        box_h = 14.2
        c.setFillColor(C_WHITE)
        c.setStrokeColor(C_LINE_STRONG)
        c.setLineWidth(0.6)
        c.roundRect(bx, y + (h - box_h) / 2, self._box_w, box_h, 2, stroke=1, fill=1)
        c.setFillColor(C_NAVY)
        c.setFont(FONT_B, 9.4)
        c.drawCentredString(bx + self._box_w / 2, y + h / 2 - 3.2, self._score_txt)


