def _table_style(n_rows: int, numeric_from: int = 1, total_row: bool = False) -> TableStyle:
    """Navy header, hairline grid, zebra body, right-aligned numerics."""
    cmds = [
        ("BACKGROUND", (0, 0), (-1, 0), C_NAVY),
        ("LINEBELOW", (0, 0), (-1, 0), 0.8, C_NAVY),
        ("TEXTCOLOR", (0, 0), (-1, 0), C_WHITE),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("ALIGN", (numeric_from, 0), (-1, -1), "RIGHT"),
        ("LINEBELOW", (0, 1), (-1, -1), 0.4, C_LINE),
        ("BOX", (0, 0), (-1, -1), 0.6, C_LINE_STRONG),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
    ]
    for r in range(2, n_rows, 2):
        cmds.append(("BACKGROUND", (0, r), (-1, r), C_ALT))
    if total_row:
        cmds += [
            ("BACKGROUND", (0, n_rows - 1), (-1, n_rows - 1), C_AMBER_TINT),
            ("LINEABOVE", (0, n_rows - 1), (-1, n_rows - 1), 0.8, C_AMBER),
            ("FONTNAME", (0, n_rows - 1), (-1, n_rows - 1), FONT_B),
        ]
    return TableStyle(cmds)


def _criteria_table(criteria: list[dict[str, Any]]) -> Table:
    header = ["Criterion", "Band", "Score", "Weight", "Contribution", "Of cap"]
    rows: list[list[Any]] = [[Paragraph(h, _CELL_H) for h in header]]
    tot_got = tot_cap = 0.0
    for c in criteria:
        score = float(c.get("score") or 0.0)
        weight = float(c.get("weight") or 0.0)
        max_score = float(c.get("max_score") or 5.0) or 5.0
        got, cap = score * weight, max_score * weight
        tot_got += got
        tot_cap += cap
        rows.append([
            Paragraph(_p(c.get("name") or "—"), _CELL_B),
            Paragraph(_p((c.get("band") or "—").title()), _CELL),
            Paragraph(f"{score:g} / {max_score:g}", _CELL),
            Paragraph(f"×{weight:g}", _CELL),
            Paragraph(f"{got:g}", _CELL_B),
            Paragraph(f"{(got / cap * 100) if cap else 0:.0f}%", _CELL),
        ])
    rows.append([
        Paragraph("Weighted total", _CELL_B),
        Paragraph("", _CELL),
        Paragraph("", _CELL),
        Paragraph("", _CELL),
        Paragraph(f"{tot_got:g}", _CELL_B),
        Paragraph(f"{(tot_got / tot_cap * 100) if tot_cap else 0:.0f}%", _CELL_B),
    ])
    widths = [CONTENT_W - 4 * 21 * mm - 16 * mm, 21 * mm, 21 * mm, 16 * mm, 21 * mm, 21 * mm]
    t = Table(rows, colWidths=widths, repeatRows=1, hAlign="LEFT")
    t.setStyle(_table_style(len(rows), numeric_from=1, total_row=True))
    return t


